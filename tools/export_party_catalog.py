#!/usr/bin/env python3
"""Export the shared preview catalog for a file://-compatible HTML study."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
source = ROOT / "godot/content/rpg_catalog.json"
target = ROOT / "docs/design/party-catalog.js"
catalog = json.loads(source.read_text())
content = "// Generated by tools/export_party_catalog.py; edit godot/content/rpg_catalog.json.\n"
content += "const PARTY_CATALOG = " + json.dumps(catalog, ensure_ascii=False, separators=(",", ":")) + ";\n"
parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
if args.check:
    if not target.exists() or target.read_text() != content:
        raise SystemExit("Party preview is stale; run python3 tools/export_party_catalog.py")
else:
    target.write_text(content)
print("Party catalog: 9 profiles, 36 authored preview builds")
